// AA-P1: the Kanban-owned Pi extension.
//
// Pi runs extensions from a file, so Kanban generates one per launch attempt and
// loads it with `pi --extension <path>`. It registers only the lifecycle
// listeners Kanban needs and forwards them through the existing
// `kanban hooks notify` boundary, so Pi keeps its own tools, prompt, model and
// user extensions untouched.
import { buildKanbanCommandParts } from "../core/kanban-command";
import { PI_HOOK_EXTENSION_FILENAME } from "./pi-session-options";

export interface PiHookExtensionInput {
	/** The Kanban-minted Pi session id this launch owns (`pi --session-id`). */
	sessionId: string;
	/** Installed Pi version when the registry discovered one, else null. */
	agentVersion?: string | null | undefined;
	/**
	 * Command the generated extension invokes. It is Kanban's own hook CLI by
	 * default; a test can point it at a recorder to observe real notifications.
	 */
	notifyCommand?: readonly string[] | undefined;
}

export function getPiHookExtensionPath(directory: string): string {
	return `${directory}/${PI_HOOK_EXTENSION_FILENAME}`;
}

function quote(value: string | null | undefined): string {
	return JSON.stringify(value ?? null);
}

/**
 * Renders the extension module. Every dynamic value is embedded as JSON, the
 * hook CLI is invoked with an argument array (never a shell string), and no
 * assistant text is ever interpolated into a command.
 */
export function buildPiHookExtensionSource(input: PiHookExtensionInput): string {
	const notifyCommand = input.notifyCommand ?? buildKanbanCommandParts(["hooks", "notify"]);
	const header = [
		"// Kanban Pi hook extension - generated by Kanban, do not edit.",
		"// Reports one Kanban task's lifecycle events through `kanban hooks notify`.",
		`const KANBAN_NOTIFY_COMMAND = ${JSON.stringify(notifyCommand)};`,
		`const KANBAN_SESSION_ID = ${quote(input.sessionId)};`,
		`const KANBAN_AGENT_VERSION = ${quote(input.agentVersion ?? null)};`,
	];

	// Plain ES2020 JavaScript with no template literals: Pi loads this file
	// through jiti, and a syntax it cannot parse would silently cost Kanban
	// every event for the task.
	const body = `import { spawn } from "node:child_process";

const MAX_ACTIVITY_CHARS = 600;
const MAX_MESSAGE_CHARS = 6000;
const MAX_RESULT_CHARS = 2000;

let rootSessionId = KANBAN_SESSION_ID;
let ownsTaskEvents = true;
let turnFailure = null;
let lastAssistantText = null;

function clipText(value, limit) {
	if (typeof value !== "string") {
		return null;
	}
	const text = value.trim();
	if (text.length === 0) {
		return null;
	}
	return text.length > limit ? text.slice(0, limit) : text;
}

function oneLine(value, limit) {
	const text = clipText(value, limit);
	return text === null ? null : text.replace(/\\s+/g, " ");
}

function contentText(content) {
	if (typeof content === "string") {
		return content;
	}
	if (!Array.isArray(content)) {
		return null;
	}
	const parts = [];
	for (const block of content) {
		if (block && typeof block === "object" && block.type === "text" && typeof block.text === "string") {
			parts.push(block.text);
		}
	}
	return parts.length > 0 ? parts.join("\\n") : null;
}

function toolResultText(result) {
	if (result === null || result === undefined) {
		return null;
	}
	const direct = contentText(result.content);
	if (direct !== null) {
		return direct;
	}
	if (typeof result === "string") {
		return result;
	}
	if (typeof result === "object") {
		const named = contentText(result.output) ?? contentText(result.text) ?? contentText(result.details);
		if (named !== null) {
			return named;
		}
		try {
			return JSON.stringify(result);
		} catch {
			return null;
		}
	}
	return String(result);
}

// Keeps the tool input a structured object while it stays small, so Kanban's
// PR recorder can still read the command, and bounds it when it is huge.
const SUMMARY_KEYS = ["command", "cmd", "file_path", "filePath", "path", "url", "description"];
function boundJsonValue(value, limit) {
	if (value === null || value === undefined) {
		return null;
	}
	if (typeof value !== "object") {
		const text = String(value);
		return text.length > limit ? text.slice(0, limit) : text;
	}
	let text = null;
	try {
		text = JSON.stringify(value);
	} catch {
		return null;
	}
	if (text !== null && text.length <= limit) {
		return value;
	}
	const summary = { truncated: true };
	for (const key of SUMMARY_KEYS) {
		const entry = value[key];
		if (typeof entry === "string") {
			summary[key] = entry.slice(0, 500);
		}
	}
	return summary;
}

function assistantText(message) {
	if (!message || message.role !== "assistant") {
		return null;
	}
	return contentText(message.content);
}

function assistantFailure(message) {
	if (!message || message.role !== "assistant") {
		return null;
	}
	const explicit = typeof message.error === "string" ? message.error : null;
	const stoppedWithError = message.stopReason === "error";
	if (!explicit && !stoppedWithError) {
		return null;
	}
	const text = contentText(message.content);
	return oneLine(explicit ?? text ?? "the model request failed", 300);
}

function modelRef(model) {
	if (!model || typeof model !== "object") {
		return null;
	}
	const provider = typeof model.provider === "string" ? model.provider : null;
	const id = typeof model.id === "string" ? model.id : null;
	if (provider && id) {
		return id.indexOf("/") >= 0 ? id : provider + "/" + id;
	}
	return id ?? provider;
}

function sessionIdOf(ctx) {
	try {
		const manager = ctx && ctx.sessionManager;
		return manager && typeof manager.getSessionId === "function" ? manager.getSessionId() : null;
	} catch {
		return null;
	}
}

function sessionFileOf(ctx) {
	try {
		const manager = ctx && ctx.sessionManager;
		return manager && typeof manager.getSessionFile === "function" ? manager.getSessionFile() : null;
	} catch {
		return null;
	}
}

// A nested Pi, or a Pi started by hand, must never move this card: it has no
// hook owner in its environment, so nothing is registered at all, and any event
// from a session other than the one Kanban created is dropped.
function ownsSession(ctx) {
	if (!ownsTaskEvents) {
		return false;
	}
	const id = sessionIdOf(ctx);
	if (!rootSessionId || !id) {
		return true;
	}
	if (id === rootSessionId) {
		return true;
	}
	ownsTaskEvents = false;
	notifyKanban("activity", [["--hook-event-name", "session_changed"], ["--notification-type", "session_changed"], ["--activity-text", "Pi switched away from the Kanban session; this card no longer follows it."]], null);
	return false;
}

function hasQueuedContinuation(ctx) {
	try {
		return typeof ctx.hasPendingMessages === "function" && ctx.hasPendingMessages() === true;
	} catch {
		return false;
	}
}

function notifyKanban(event, flags, payload) {
	try {
		if (!process.env.KANBAN_HOOK_TASK_ID) {
			return;
		}
		const args = KANBAN_NOTIFY_COMMAND.slice(1).concat(["--event", event, "--source", "pi"]);
		for (const flag of flags || []) {
			const value = flag[1];
			if (typeof value === "string" && value.length > 0) {
				args.push(flag[0], value);
			}
		}
		if (payload) {
			args.push("--metadata-base64", Buffer.from(JSON.stringify(payload), "utf8").toString("base64"));
		}
		const child = spawn(KANBAN_NOTIFY_COMMAND[0], args, { stdio: "ignore", windowsHide: true });
		child.on("error", () => {});
		if (typeof child.unref === "function") {
			child.unref();
		}
	} catch {
		// A failed notification is never worth failing the agent's tool call.
	}
}

function basePayload(ctx, hookEventName) {
	return {
		source: "pi",
		hook_event_name: hookEventName,
		pi_agent_version: KANBAN_AGENT_VERSION,
		pi_session_id: sessionIdOf(ctx),
		pi_session_file: sessionFileOf(ctx),
	};
}

export default function kanbanPiHooks(pi) {
	if (!process.env.KANBAN_HOOK_TASK_ID) {
		// No Kanban hook owner: a child Pi session never inherits this card.
		return;
	}

	pi.on("session_start", async (event, ctx) => {
		const id = sessionIdOf(ctx);
		if (rootSessionId && id && id !== rootSessionId) {
			ownsTaskEvents = false;
		} else {
			rootSessionId = rootSessionId || id;
		}
		if (!ownsSession(ctx)) {
			return;
		}
		const payload = basePayload(ctx, "session_start");
		payload.pi_session_reason = event && event.reason;
		notifyKanban(
			"activity",
			[
				["--hook-event-name", "session_start"],
				["--activity-text", "Pi session " + (event && event.reason ? event.reason : "started")],
			],
			payload,
		);
	});

	pi.on("agent_start", async (_event, ctx) => {
		if (!ownsSession(ctx)) {
			return;
		}
		turnFailure = null;
		notifyKanban(
			"to_in_progress",
			[
				["--hook-event-name", "agent_start"],
				["--activity-text", "Pi is working"],
			],
			basePayload(ctx, "agent_start"),
		);
	});

	pi.on("message_end", async (event, ctx) => {
		if (!ownsSession(ctx)) {
			return;
		}
		const message = event && event.message;
		const text = assistantText(message);
		if (text) {
			lastAssistantText = text;
		}
		const failure = assistantFailure(message);
		if (failure) {
			turnFailure = failure;
		}
	});

	pi.on("tool_execution_end", async (event, ctx) => {
		if (!ownsSession(ctx)) {
			return;
		}
		const toolName = oneLine(event && event.toolName, 120) ?? "tool";
		const payload = basePayload(ctx, "tool_execution_end");
		payload.tool_name = toolName;
		payload.tool_input = boundJsonValue(event && event.args, MAX_RESULT_CHARS);
		payload.tool_response = { output: clipText(toolResultText(event && event.result), MAX_RESULT_CHARS) };
		if (event && event.isError === true) {
			turnFailure = "the " + toolName + " tool failed";
			notifyKanban(
				"activity",
				[
					["--hook-event-name", "tool_execution_end"],
					["--tool-name", toolName],
					["--notification-type", "error"],
					["--activity-text", "Failed " + toolName],
				],
				payload,
			);
			return;
		}
		notifyKanban(
			"activity",
			[
				["--hook-event-name", "tool_execution_end"],
				["--tool-name", toolName],
				["--activity-text", "Completed " + toolName],
			],
			payload,
		);
	});

	pi.on("model_select", async (event, ctx) => {
		if (!ownsSession(ctx)) {
			return;
		}
		const ref = modelRef(event && event.model);
		const payload = basePayload(ctx, "model_select");
		payload.pi_model = ref;
		notifyKanban(
			"activity",
			[
				["--hook-event-name", "model_select"],
				["--activity-text", ref ? "Model: " + ref : "Model changed"],
			],
			payload,
		);
	});

	// Pi has no tool-approval prompts, but an extension dialog blocks the run
	// until the user answers it in the terminal.
	pi.on("ui_prompt_start", async (event, ctx) => {
		if (!ownsSession(ctx)) {
			return;
		}
		const payload = basePayload(ctx, "ui_prompt_start");
		payload.notification_type = "permission_prompt";
		notifyKanban(
			"to_review",
			[
				["--hook-event-name", "ui_prompt_start"],
				["--notification-type", "permission_prompt"],
				["--activity-text", "Pi is waiting for input in the terminal"],
			],
			payload,
		);
	});

	// Only a fully settled run may look like completion: Pi fires this after
	// automatic retries, compaction and queued continuations are done.
	pi.on("agent_settled", async (event, ctx) => {
		if (!ownsSession(ctx)) {
			return;
		}
		if (hasQueuedContinuation(ctx)) {
			return;
		}
		const payload = basePayload(ctx, "agent_settled");
		if (event && event.aborted === true) {
			turnFailure = null;
			lastAssistantText = null;
			payload.pi_aborted = true;
			notifyKanban(
				"activity",
				[
					["--hook-event-name", "agent_settled"],
					["--notification-type", "aborted"],
					["--activity-text", "Pi stopped before finishing the turn"],
				],
				payload,
			);
			return;
		}
		if (turnFailure) {
			const failure = turnFailure;
			turnFailure = null;
			lastAssistantText = null;
			payload.pi_error = failure;
			notifyKanban(
				"activity",
				[
					["--hook-event-name", "agent_settled"],
					["--notification-type", "error"],
					["--activity-text", "Pi stopped: " + oneLine(failure, MAX_ACTIVITY_CHARS)],
				],
				payload,
			);
			return;
		}
		const finalMessage = clipText(lastAssistantText, MAX_MESSAGE_CHARS);
		lastAssistantText = null;
		if (finalMessage) {
			payload.final_message = finalMessage;
		}
		notifyKanban(
			"to_review",
			[
				["--hook-event-name", "agent_settled"],
				["--activity-text", finalMessage ? "Final: " + oneLine(finalMessage, MAX_ACTIVITY_CHARS) : "Pi finished the turn"],
				["--final-message", finalMessage],
			],
			payload,
		);
	});

	// The card owns exactly one Pi session. Rebinding it is a Kanban action, so
	// Pi's own switch and fork commands are refused instead of silently moving
	// this task's events into another conversation.
	pi.on("session_before_switch", async (_event, ctx) => {
		if (!ownsSession(ctx)) {
			return undefined;
		}
		notifyKanban(
			"activity",
			[
				["--hook-event-name", "session_before_switch"],
				["--notification-type", "session_pinned"],
				["--activity-text", "Kanban kept this task in its own Pi session"],
			],
			basePayload(ctx, "session_before_switch"),
		);
		return { cancel: true };
	});

	pi.on("session_before_fork", async (_event, ctx) => {
		if (!ownsSession(ctx)) {
			return undefined;
		}
		notifyKanban(
			"activity",
			[
				["--hook-event-name", "session_before_fork"],
				["--notification-type", "session_pinned"],
				["--activity-text", "Kanban kept this task in its own Pi session"],
			],
			basePayload(ctx, "session_before_fork"),
		);
		return { cancel: true };
	});
}
`;

	return `${header.join("\n")}\n${body}`;
}
